"""Export the SituationSimulator spreadsheet into data.js for the playtest table.

Usage:
    python tools/export_data.py [path/to/SituationSimulator.xlsx]

Re-run this whenever the spreadsheet changes. Reads cell values only, so the
random formulas on the Main sheet don't matter; only its icon column (M) is used.
"""

import json
import sys
import warnings
from pathlib import Path

import openpyxl

warnings.filterwarnings("ignore")  # openpyxl warns about Excel data-validation extensions

DEFAULT_XLSX = Path.home() / "Dropbox" / "CardRPG" / "SituationSimulator.xlsx"
OUT = Path(__file__).resolve().parent.parent / "data.js"


def text(v):
    return "" if v is None else str(v).strip()


def table_column(ws, name):
    """Values of a single-column Excel table, minus its header."""
    ref = ws.tables[name].ref
    return [text(row[0].value) for row in ws[ref][1:] if text(row[0].value)]


def column(ws, col, first_row):
    out = []
    row = first_row
    while text(ws[f"{col}{row}"].value):
        out.append(text(ws[f"{col}{row}"].value))
        row += 1
    return out


def card_block(ws, header_row, n_rows):
    """A block on the cards sheet: header row of names, n_rows of attributes below each."""
    cards = []
    col = 1
    while text(ws.cell(header_row, col).value):
        cards.append({
            "name": text(ws.cell(header_row, col).value),
            "lines": [text(ws.cell(header_row + 1 + i, col).value) for i in range(n_rows)],
        })
        col += 1
    return cards


def icons(ws, first_row, last_row):
    return [text(ws[f"M{r}"].value) for r in range(first_row, last_row + 1)]


def main(xlsx):
    wb = openpyxl.load_workbook(xlsx, data_only=True)
    pcs, cards, situ, other, board = wb["PCs"], wb["cards"], wb["situations"], wb["other"], wb["Main"]

    situations = []
    for r in range(2, situ.max_row + 1):
        desc = text(situ[f"A{r}"].value)
        if not desc:
            continue
        situations.append({
            "name": text(situ[f"J{r}"].value),
            "description": desc,
            "escalations": [text(situ[f"B{r}"].value), text(situ[f"C{r}"].value)],
            "approaches": [text(situ[f"{c}{r}"].value) for c in "DEF"],
            "risks": [text(situ[f"{c}{r}"].value) for c in "GHI"],
        })

    # Main sheet column M holds the icon for each element card's header and attribute lines.
    macguffin_icons = icons(board, 4, 8)
    ally_icons = icons(board, 13, 17)
    villain_icons = icons(board, 22, 26)
    location_icons = icons(board, 31, 40)

    data = {
        "approaches": table_column(other, "approaches"),
        "resources": table_column(other, "resources"),
        "players": column(other, "A", 8),
        "concepts": table_column(pcs, "concept"),
        "troubles": table_column(pcs, "trouble"),
        "firstNames": table_column(pcs, "first"),
        "lastNames": table_column(pcs, "last"),
        "boons": table_column(pcs, "boon"),
        "boonStates": table_column(pcs, "state"),
        "relationships": table_column(pcs, "rel"),
        "placeAdjectives": table_column(cards, "placenames"),
        "macguffins": {"icons": macguffin_icons, "cards": card_block(cards, 1, 4)},
        "locations": {"icons": location_icons, "cards": card_block(cards, 7, 9)},
        "villains": {"icons": villain_icons, "cards": card_block(cards, 27, 4)},
        "allies": {"icons": ally_icons, "cards": card_block(cards, 33, 4)},
        "situations": situations,
    }

    OUT.write_text(
        "// Generated by tools/export_data.py from SituationSimulator.xlsx. Do not edit by hand.\n"
        f"window.GAME_DATA = {json.dumps(data, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT} ({len(situations)} situations, {len(data['concepts'])} concepts)")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_XLSX)
